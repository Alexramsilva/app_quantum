@st.cache_data(ttl=3600)
def download_prices(tickers):

    data = yf.download(
        list(tickers),
        period="2y",
        auto_adjust=True,
        progress=False,
        threads=True
    )

    if data.empty:
        raise ValueError(
            "Yahoo Finance no devolvió datos."
        )

    if isinstance(data.columns, pd.MultiIndex):

        if "Close" in data.columns.get_level_values(0):
            prices = data["Close"]

        elif "Close" in data.columns.get_level_values(1):
            prices = data.xs(
                "Close",
                axis=1,
                level=1
            )

        else:
            raise ValueError(
                "No se encontró la columna Close."
            )

    else:

        prices = data["Close"]

        if isinstance(prices, pd.Series):
            prices = prices.to_frame(
                name=tickers[0]
            )

    if isinstance(prices, pd.Series):
        prices = prices.to_frame()

    return prices


# =====================================================
# 5. ESTIMACIÓN DE PARÁMETROS
# =====================================================

def estimate_parameters(prices):

    returns = prices.pct_change().dropna()

    # Rendimientos anualizados
    mu = returns.mean() * 252

    # Matriz de covarianzas anualizada
    covariance = returns.cov() * 252

    # Volatilidad anualizada
    sigma = np.sqrt(
        np.diag(covariance.values)
    )

    return returns, mu, covariance, sigma


# =====================================================
# 6. CONSTRUCCIÓN DEL QUBO
# =====================================================

def build_qubo(
    tickers,
    mu,
    covariance,
    lambda_risk,
    K,
    penalty
):

    qp = QuadraticProgram()

    n = len(tickers)

    # Variables binarias
    for t in tickers:
        qp.binary_var(name=t)

    # Función objetivo
    # Maximizar:
    # mu'x - lambda*x' Sigma x

    linear = {
        tickers[i]: float(mu.iloc[i])
        for i in range(n)
    }

    quadratic = {}

    # Términos diagonales y cruzados.
    # El factor 2 en los términos cruzados
    # reproduce exactamente x' Sigma x.

    for i in range(n):

        quadratic[
            (tickers[i], tickers[i])
        ] = float(
            -lambda_risk * covariance.iloc[i, i]
        )

        for j in range(i + 1, n):

            quadratic[
                (tickers[i], tickers[j])
            ] = float(
                -2 * lambda_risk * covariance.iloc[i, j]
            )

    qp.maximize(
        linear=linear,
        quadratic=quadratic
    )

    # Restricción de cardinalidad
    qp.linear_constraint(
        linear={
            t: 1 for t in tickers
        },
        sense="==",
        rhs=K,
        name="cardinalidad"
    )

    return qp


# =====================================================
# 7. OPTIMIZACIÓN QAOA
# =====================================================

####

def run_qaoa(qp, reps, maxiter, shots, penalty=100.0):

    sampler = StatevectorSampler(
        default_shots=shots,
        seed=42
    )

    optimizer = COBYLA(
        maxiter=maxiter
    )

    qaoa = QAOA(
        sampler=sampler,
        optimizer=optimizer,
        reps=reps
    )

    eigen_optimizer = MinimumEigenOptimizer(
        qaoa,
        penalty=penalty
    )

    result = eigen_optimizer.solve(qp)

    return result

